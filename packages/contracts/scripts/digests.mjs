// Writes (or, with --check, compares) test/fixtures/digests.json: every EIP-712 digest the
// checkout's signers produce, computed by viem from fixed inputs and the shared type
// definitions. The Foundry suite recomputes each digest by hand and against the contract.
//   node scripts/digests.mjs           write the fixture
//   node scripts/digests.mjs --check   exit 1 if the committed fixture differs

import { readFileSync, writeFileSync } from 'node:fs';
import { getAddress, hashStruct, hashTypedData, keccak256, toHex } from 'viem';
import { config } from '@graphpay/config';
import {
  cancelTypes,
  checkoutDomain,
  eip2612Types,
  permit2Domain,
  permitHash,
  permitSingleTypes,
  permitWitnessTypes,
  renewalOrderId,
  subscribeTypes,
  tokenDomain,
  WITNESS_TYPE_STRING,
} from '../typed-data.mjs';

const FIXTURE = new URL('../test/fixtures/digests.json', import.meta.url);

// Made-up fixture values (no real wallet or contract): addresses and ids derived from labels.
const word = (label) => keccak256(toHex(`graphpay fixture: ${label}`));
const address = (label) => getAddress(`0x${word(label).slice(-40)}`);

export function buildFixture() {
  const chainId = config.networks.whitechain.chainId;
  const token = config.whitechain.tokens.usdt;
  const permit2 = config.whitechain.system.permit2;
  const checkout = address('checkout');

  const order = {
    orderId: `0x${(BigInt(word('order')) >> 1n).toString(16).padStart(64, '0')}`,
    parentOrderId: `0x${'0'.repeat(64)}`,
    buyerNode: word('buyer node'),
    shopNode: word('shop node'),
    payerNode: word('payer node'),
    merchant: address('merchant'),
    amountMicro: 4_800_000,
    deadline: 1_793_000_000,
    kind: 0,
  };
  const mandateHash = word('mandate');
  const permit = { nonce: BigInt(order.orderId).toString(), deadline: order.deadline };
  const approval = { owner: address('payer'), value: 50_000_000, nonce: 3, deadline: 1_793_000_600 };
  const permitSingle = {
    details: { token: token.address, amount: 400_000, expiration: 1_794_000_000, nonce: 2 },
    spender: checkout,
    sigDeadline: 1_793_000_300,
  };
  const sub = {
    subId: word('subscription'),
    subscriberNode: word('subscriber node'),
    shopNode: word('shop node'),
    payerNode: `0x${'0'.repeat(64)}`,
    merchant: address('merchant'),
    amountMicro: 400_000,
    period: 120,
    firstChargeAt: 1_792_999_000,
  };
  const cancel = { subId: sub.subId, deadline: 1_793_000_900 };

  const witness = { ...order, mandateHash };
  const ps = { ...permitSingle, details: { ...permitSingle.details } };
  const digests = {
    witnessStruct: hashStruct({ types: permitWitnessTypes, primaryType: 'GraphPayOrder', data: witness }),
    witness: hashTypedData({
      domain: permit2Domain(chainId, permit2),
      types: permitWitnessTypes,
      primaryType: 'PermitWitnessTransferFrom',
      message: {
        permitted: { token: token.address, amount: BigInt(order.amountMicro) },
        spender: checkout,
        nonce: BigInt(permit.nonce),
        deadline: BigInt(permit.deadline),
        witness,
      },
    }),
    eip2612: hashTypedData({
      domain: tokenDomain(chainId, token),
      types: eip2612Types,
      primaryType: 'Permit',
      message: { ...approval, spender: permit2 },
    }),
    permitSingle: hashTypedData({
      domain: permit2Domain(chainId, permit2),
      types: permitSingleTypes,
      primaryType: 'PermitSingle',
      message: ps,
    }),
    permitHash: permitHash(ps),
    subscribe: hashTypedData({
      domain: checkoutDomain(chainId, checkout),
      types: subscribeTypes,
      primaryType: 'Subscribe',
      message: { ...sub, permitHash: permitHash(ps) },
    }),
    cancel: hashTypedData({
      domain: checkoutDomain(chainId, checkout),
      types: cancelTypes,
      primaryType: 'Cancel',
      message: cancel,
    }),
  };

  // Addresses from the config are named by path, never written here (acceptance A7).
  return {
    about:
      'Generated by packages/contracts/scripts/digests.mjs with viem; checked by `pnpm test` and recomputed by hand in test/Digests.t.sol. Fixture values are made up; the token and Permit2 are read from the config.',
    config: { chainId: '.networks.whitechain.chainId', token: '.whitechain.tokens.usdt', permit2: '.whitechain.system.permit2' },
    checkout,
    order,
    mandateHash,
    permit,
    approval,
    permitSingle: { amount: permitSingle.details.amount, expiration: permitSingle.details.expiration, nonce: permitSingle.details.nonce, sigDeadline: permitSingle.sigDeadline },
    sub,
    cancel: { deadline: cancel.deadline },
    renewalOrderId2: renewalOrderId(sub.subId, 2),
    witnessTypeString: WITNESS_TYPE_STRING,
    digests,
  };
}

export const serialise = (fixture) => `${JSON.stringify(fixture, null, 2)}\n`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = serialise(buildFixture());
  if (process.argv.includes('--check')) {
    const committed = readFileSync(FIXTURE, 'utf8');
    if (committed !== text) {
      console.error('digests.json differs from what viem computes now: run node scripts/digests.mjs');
      process.exitCode = 1;
    } else {
      console.log('digests.json matches viem');
    }
  } else {
    writeFileSync(FIXTURE, text);
    console.log('wrote test/fixtures/digests.json');
  }
}
