// Writes (or, with --check, compares) the committed ABI from the forge build output, so
// packages that never run forge (the facilitator, the mirror, the website) import it.
//   forge build && node scripts/abi.mjs           write abi/GraphPayCheckout.json and .d.ts
//   forge build && node scripts/abi.mjs --check   exit 1 if the committed ABI is stale

import { readFileSync, writeFileSync } from 'node:fs';

const at = (path) => new URL(`../${path}`, import.meta.url);
const artifact = JSON.parse(readFileSync(at('out/GraphPayCheckout.sol/GraphPayCheckout.json'), 'utf8'));
const json = `${JSON.stringify(artifact.abi, null, 2)}\n`;
const dts = `// Generated by scripts/abi.mjs from the forge build; do not edit.\nexport declare const checkoutAbi: readonly ${JSON.stringify(artifact.abi)};\n`;

if (process.argv.includes('--check')) {
  const stale = [['abi/GraphPayCheckout.json', json], ['abi/GraphPayCheckout.d.ts', dts]].filter(
    ([path, text]) => readFileSync(at(path), 'utf8') !== text,
  );
  for (const [path] of stale) console.error(`${path} is stale: run forge build && node scripts/abi.mjs`);
  if (stale.length) process.exitCode = 1;
  else console.log('ABI matches the build');
} else {
  writeFileSync(at('abi/GraphPayCheckout.json'), json);
  writeFileSync(at('abi/GraphPayCheckout.d.ts'), dts);
  console.log(`wrote abi/GraphPayCheckout.json (${artifact.abi.length} entries)`);
}
