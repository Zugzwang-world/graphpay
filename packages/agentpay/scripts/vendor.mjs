// Regenerates src/vendor/: the checkout ABI, the EIP-712 shapes and the Whitechain Sepolia
// defaults, copied from the workspace so the published package has no workspace dependency.
//   node scripts/vendor.mjs          write the files
//   node scripts/vendor.mjs --check  exit 1 when a file is out of date (the test runs this)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, '..');
const root = join(pkg, '..', '..');
const read = (p) => readFileSync(p, 'utf8');

export function build() {
  const abi = JSON.parse(read(join(root, 'packages/contracts/abi/GraphPayCheckout.json')));
  const config = JSON.parse(read(join(root, 'packages/config/graphpay.config.json')));
  const net = config.networks.whitechain;
  const w = config.whitechain;
  const defaults = {
    name: net.name,
    chainId: net.chainId,
    nativeSymbol: net.nativeSymbol,
    explorer: net.explorer,
    publicRpcs: net.publicRpcs.map((r) => r.url),
    permit2: w.system.permit2,
    multicall3: w.system.multicall3,
    checkout: { address: w.contracts.checkout.address, deployBlock: w.contracts.checkout.deployBlock, token: w.contracts.checkout.token },
    tokens: { [w.contracts.checkout.token]: w.tokens[w.contracts.checkout.token] },
    neverUse: w.tokens.neverUse,
  };
  const banner = (what) => `// GENERATED by scripts/vendor.mjs from ${what}. Do not edit; run \`node scripts/vendor.mjs\`.\n`;
  return {
    'src/vendor/abi.mjs': `${banner('packages/contracts/abi/GraphPayCheckout.json')}export const checkoutAbi = ${JSON.stringify(abi)};\n`,
    'src/vendor/typed-data.mjs': `${banner('packages/contracts/typed-data.mjs')}${read(join(root, 'packages/contracts/typed-data.mjs'))}`,
    'src/vendor/defaults.mjs': `${banner('packages/config/graphpay.config.json')}// Whitechain Sepolia (chain 1874) facts. The checkout here is the GraphPay demo deployment: only its\n// granted relayers can settle, so a developer runs it on an anvil fork or deploys their own (README).\nexport const defaults = ${JSON.stringify(defaults, null, 2)};\n`,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = build();
  let stale = 0;
  for (const [rel, text] of Object.entries(files)) {
    const file = join(pkg, rel);
    if (process.argv.includes('--check')) {
      if (!existsSync(file) || read(file) !== text) {
        console.log(`out of date: ${rel}`);
        stale++;
      }
    } else writeFileSync(file, text);
  }
  if (stale) process.exitCode = 1;
}
