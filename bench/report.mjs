// bench/BENCHMARK-LIVE.md from the benchmark's rows: plain language first, then tables,
// then caveats. Reads and bytes are the result; times stay in the CSVs (ADR-0042).

// The lab's live call counts at size S (planning/SPEC/BENCHMARK.md §4, Rabdi,
// 2026-11-04, before the event's merged columns): only to flag a count that differs.
const LAB_S = { plain: { Q1: 3, Q2: 5, Q3: 2, Q4: 2, Q5: 3, Q6: 2 }, graph: { Q1: 3, Q2: 2, Q3: 3, Q4: 2, Q5: 5, Q6: 2 }, parallel: 6 };

const ASKS = {
  Q1: "the featured shop's refund rate and 90-day orders",
  Q2: 'the top 10 shops by sales, city-wide',
  Q3: "the persona's agents' spend by shop this week",
  Q4: 'agents that paid a shop this week that later refunded someone else',
  Q5: "a payment path from the persona's paying agent to the trap shop, within 3 hops",
  Q6: "the featured shop's depth-2 neighbourhood over this week's payments",
};

const kb = (b) => (Number(b) / 1024).toFixed(1);
const yes = (v) => (v ? 'yes' : 'no');
const table = (cols, rows) => [`| ${cols.join(' | ')} |`, `|${cols.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');

export function report({ summary, questionRows, parallelRows, writeRows }) {
  const row = (q, mode) => questionRows.find((r) => r.question === q && r.mode === mode);
  const par = (f) => parallelRows.find((r) => r.mode === 'plain' && String(r.in_flight) === String(f));
  const graphQ2 = parallelRows.find((r) => r.mode === 'graph');
  const pages = Math.ceil(summary.payRows / 100);
  const seq = par(1);
  const allAtOnce = par('all');
  const plainQ2 = row('Q2', 'plain');
  const notFewer = ['Q1', 'Q3', 'Q4', 'Q5', 'Q6'].filter((q) => Number(row(q, 'graph').calls) >= Number(row(q, 'plain').calls));
  const graphAllRight = questionRows.filter((r) => r.mode === 'graph').every((r) => r.correct);
  const plainAllRight = questionRows.filter((r) => r.mode === 'plain').every((r) => r.correct);
  const writes = Object.fromEntries(writeRows.map((w) => [w.store, w]));

  const d6 = [
    ['Graph Arkiv Q2 reads', '2', String(graphQ2.calls), String(graphQ2.calls) === '2'],
    [`plain Q2, one page at a time: ceil(R / 100), R = ${summary.payRows}`, String(pages), String(seq.calls), String(seq.calls) === String(pages)],
    ['plain Q2 in parallel: that + 1 (the count())', String(pages + 1), [4, 8, 16, 'all'].map((f) => par(f).calls).join(', '), [4, 8, 16, 'all'].every((f) => String(par(f).calls) === String(pages + 1))],
    ['Graph Arkiv correct (by identity)', 'every run', yes(graphQ2.correct && row('Q2', 'graph').correct), graphQ2.correct && row('Q2', 'graph').correct],
    ['plain correct (by name)', 'every run', yes(plainQ2.correct && parallelRows.filter((r) => r.mode === 'plain').every((r) => r.correct)), plainQ2.correct && parallelRows.filter((r) => r.mode === 'plain').every((r) => r.correct)],
  ];
  const d6Pass = d6.every((c) => c[3]);

  const lab = [];
  for (const q of Object.keys(ASKS)) for (const mode of ['plain', 'graph']) lab.push([q, mode === 'graph' ? 'Graph Arkiv' : 'plain', LAB_S[mode][q], row(q, mode).calls, String(LAB_S[mode][q]) === String(row(q, mode).calls) ? 'same' : '**differs**']);
  lab.push(['Q2', 'plain, parallel', LAB_S.parallel, allAtOnce.calls, String(LAB_S.parallel) === String(allAtOnce.calls) ? 'same' : '**differs**']);
  const differs = lab.filter((r) => r[4] !== 'same');

  return `# Live benchmark: plain Arkiv against Graph Arkiv

**SYNTHETIC DATA.** Dataset \`${summary.dataset}\` (size ${summary.size}), live on Arkiv's ${summary.backend} testnet, blocks ${summary.blockFrom} to ${summary.blockTo}, commit \`${summary.commit}\`, run ${summary.date}. Generated by \`node bench/run.mjs\` from the CSVs in \`bench/results/\`.

## In plain words

Arkiv has no SUM. To rank the city's shops by sales, plain Arkiv code must read every payment and renewal row (${summary.payRows} of them here) and add them up itself. Graph Arkiv keeps running totals for every shop, written with each payment, so the ranking is one sorted read of the totals plus one read of the names.

- **The city-wide top 10 takes Graph Arkiv ${graphQ2.calls} reads against ${seq.calls}** for plain code reading one page at a time, and against ${allAtOnce.calls} when plain asks for every page at once (one extra read to count the pages first). Plain moves ${kb(plainQ2.bytes)} KB for it, Graph Arkiv ${kb(row('Q2', 'graph').bytes)} KB.
- **${graphAllRight ? 'Every Graph Arkiv answer was right' : 'Not every Graph Arkiv answer was right (see the table)'}**, by identity: a re-registered name starts a new history. ${plainAllRight ? 'Plain code was right by name on every question' : 'Plain code was not right by name on every question'}${plainQ2.matches_identity_truth ? '.' : ", but wrong by identity on the top 10: it credits the re-registered shop's earlier holder's sales to the new holder."}
- **Where Graph Arkiv does not need fewer reads:** ${notFewer.length ? notFewer.map((q) => `${q} (${row(q, 'graph').calls} against ${row(q, 'plain').calls})`).join(', ') : 'none at this size'}. The win is aggregates, and it grows with the data: plain's top-10 reads grow with every payment, Graph Arkiv's stay at 2. The larger city waits for the founder's final story (ADR-0049).

A line that is safe to quote: *"On Arkiv's live testnet, with a synthetic city of ${summary.payRows} payment and renewal rows, the city-wide top-10 ranking takes Graph Arkiv ${graphQ2.calls} reads. Plain Arkiv code must read every row: ${seq.calls} reads one page at a time, ${allAtOnce.calls} with every page requested at once."*

## Acceptance D6 (as amended: calls exact, times recorded but not scored)

${table(['check', 'expected', 'measured', 'result'], d6.map((c) => [c[0], c[1], c[2], c[3] ? 'pass' : '**fail**']))}

**D6: ${d6Pass ? 'pass' : 'fail'}.** D7 (size M): blocked, waiting for the locked story.

## The six questions (reads and bytes; ${questionRows[0].runs} runs each after a warm-up)

${table(
  ['Q', 'question', 'plain reads', 'plain KB', 'Graph Arkiv reads', 'Graph Arkiv KB', 'plain right by name', 'plain right by identity', 'Graph Arkiv right'],
  Object.entries(ASKS).map(([q, text]) => {
    const p = row(q, 'plain');
    const g = row(q, 'graph');
    return [q, text, p.calls, kb(p.bytes), g.calls, kb(g.bytes), yes(p.correct), yes(p.matches_identity_truth), yes(g.correct)];
  }),
)}

## The top 10 at plain's fastest (${graphQ2.runs} interleaved rounds)

${table(
  ['mode', 'requests in flight', 'reads', 'KB', 'right', 'non-200 responses', '429s'],
  parallelRows.map((r) => [r.mode === 'graph' ? 'Graph Arkiv' : 'plain', r.mode === 'graph' ? '-' : r.in_flight === 1 ? '1 (one page at a time)' : r.in_flight === 'all' ? `all (${pages} pages)` : r.in_flight, r.calls, kb(r.bytes), yes(r.correct), r.non_200, r.n_429]),
)}

At ${pages} pages, 8, 16 and "all" in flight are the same request pattern.

## Against the lab's counts

The lab ran the same questions live on Rabdi on 2026-11-04, before the event's merged model. Only the read counts are compared here.

${table(['Q', 'mode', 'lab reads', 'event reads', ''], lab)}

${differs.length ? `**${differs.length} count${differs.length > 1 ? 's differ' : ' differs'}**: ${differs.map((r) => `${r[0]} ${r[1]} (${r[2]} in the lab, ${r[3]} here)`).join('; ')}. The event's generator does not reproduce the lab's city row for row, and the event's GraphQL resolvers are its own, so a count that differs is expected; the exact checks are D6's.` : 'Every count matches the lab.'}

## Writes (seeding the city)

${table(['store', 'transactions', 'creates', 'patches', 'tGLM'], writeRows.map((w) => [w.store, w.transactions, w.creates, w.patches, w.tglm]))}

Graph Arkiv's store costs more to write (${writes.graph?.tglm} against ${writes.plain?.tglm} tGLM for plain): every money event also updates the totals at both ends. That is the price of the 2-read aggregates.

## What to claim, and what not

- **Claim:** one GraphQL call answers any of the six questions; aggregates cost a constant 2 reads while plain code must read every payment, so the gap grows with the data; answers are right by identity (epochs); totals are verifiable (\`verify\` recounts them with \`count()\`).
- **Do not claim:** fewer reads for this week's traversals${notFewer.length ? ` (${notFewer.join(', ')} here)` : ''}; a speed win at this size (times are in the CSVs and are not the result, ADR-0042); emulated numbers as live ones; cheaper writes.

## Caveats

- Synthetic data, labelled on every row; one small city (size ${summary.size}); one machine, one network, a testnet days old.
- Reads (JSON-RPC calls) and bytes (request plus response bodies, without headers; 1 KB = 1,024 bytes) are counted by one shared metered transport for both modes. Times are recorded in the CSVs only.
- HTTP: ${summary.http.responses} responses logged, ${summary.http.non200} not 200, ${summary.http.n429} with 429; lowest rate-limit headroom ${summary.http.lowestRemaining} (\`bench/results/http-${summary.size}.csv\`: status, time and the \`ratelimit\` header, never the URL).
${summary.q4Empty ? "- Q4's true answer is empty at this size: no agent paid a shop this week that later refunded someone else. The reads are still counted; both modes must find it empty.\n" : ''}- Plain code is best effort, written by hand: \`count()\` wherever a count answers, OR batches inside the 64-leaf budget, projections, a two-ended path search.

## Files

\`bench/results/questions-${summary.size}.csv\`, \`q2-parallel-${summary.size}.csv\`, \`writes-${summary.size}.csv\`, \`http-${summary.size}.csv\`; the harness \`bench/run.mjs\`; the questions both ways in \`packages/money-graph/src/bench.mjs\`; the truth in \`packages/city/src/bench.mjs\`.
`;
}
