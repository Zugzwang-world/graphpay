/**
 * Every caption, hint and funny line lives here (DESIGN_INSTRUCTIONS.md 11).
 * Lines take {placeholders} filled from the story data or the adapter, so no
 * name, shop or price is typed into a component. Arrays hold several lines
 * for one situation; `pick` chooses one at random.
 *
 * Placeholder copy: memes and jokes will be replaced by the separately
 * supplied asset files (DESIGN_INSTRUCTIONS.md 15).
 */

export type Vars = Record<string, string | number | undefined>;

export function fill(template: string, vars: Vars = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] === undefined ? `{${k}}` : String(vars[k])));
}

export function pick(lines: readonly string[], vars: Vars = {}, seed?: number): string {
  const i = seed === undefined ? Math.floor(Math.random() * lines.length) : Math.abs(seed) % lines.length;
  return fill(lines[i] ?? lines[0] ?? '', vars);
}

